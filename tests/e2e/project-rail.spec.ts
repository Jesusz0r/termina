import { test, expect } from "./fixtures.ts";
import { writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { activeProject, savedPlanProject } from "./saved-plan-project.ts";
import { readVerifyStages, writeVerifyPackage } from "../fixtures/verify-package.ts";

test("the project rail navigates exact same-name roots while native Attention stays visible with canonical counts", async ({ page, projectRoot, runRoot }) => {
  await expect(page.locator("#splash")).toBeHidden();
  await expect(page.locator("#btn-all-projects, #project-overview, #project-details, #project-work-inspector, #task-composer")).toHaveCount(0);
  const original = await activeProject(page);
  const first = await savedPlanProject(page, projectRoot, runRoot, 1, [[]]);
  await writeFile(join(first.project.cwd, ".gitignore"), "/stages.jsonl\nnode_modules/\n");
  await writeVerifyPackage(first.project.cwd, { test: "termina-verify-fixture fail" });
  const second = await savedPlanProject(page, projectRoot, runRoot, 2, [[]]);
  expect(basename(first.project.cwd)).toBe(basename(second.project.cwd));
  expect(first.project.cwd).not.toBe(second.project.cwd);
  const rail = page.locator("#project-tabs");
  const attention = page.locator("#project-bar #attention-view");
  const heading = attention.locator("#attention-heading");
  await expect(attention).toBeVisible();
  await expect(heading).toHaveJSProperty("tagName", "H2");
  expect(await heading.evaluate((element) => [...element.childNodes].filter((node) => node.nodeType === Node.TEXT_NODE).map((node) => node.textContent).join("").trim())).toBe("Attention");
  await expect(heading.locator(".attention-count")).toHaveText("0");
  for (const attribute of ["role", "aria-expanded", "aria-controls", "tabindex"]) expect(await heading.getAttribute(attribute)).toBeNull();
  await expect(page.getByRole("button", { name: /^Attention(?:\s|$)/, includeHidden: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Close attention", exact: true, includeHidden: true })).toHaveCount(0);
  expect(await attention.evaluate((element) => {
    const projects = element.parentElement!.querySelector(":scope > .project-rail-heading")!;
    return Boolean(element.compareDocumentPosition(projects) & Node.DOCUMENT_POSITION_FOLLOWING);
  })).toBe(true);
  const row = (id: string) => rail.locator(`.project-tab[data-project-id="${id}"]`);
  const select = (id: string) => row(id).locator(".project-select");
  for (const project of [first.project, second.project]) {
    await expect(row(project.id).locator(".project-path")).toHaveText(project.cwd);
    await expect(row(project.id).locator(".project-working")).toHaveText("0 working");
    await expect(row(project.id).locator(".project-attention")).toHaveText("0 attention");
  }
  await select(first.project.id).click();
  await expect.poll(() => activeProject(page).then((project) => project.cwd)).toBe(first.project.cwd);
  await expect(select(first.project.id)).toHaveAttribute("aria-current", "page");
  await expect(select(second.project.id)).not.toHaveAttribute("aria-current", "page");
  await select(first.project.id).focus();
  await page.keyboard.press("Home");
  await expect(select(original.id)).toBeFocused();
  await page.keyboard.press("ArrowDown");
  await expect(select(first.project.id)).toBeFocused();
  await page.keyboard.press("End");
  await expect(select(second.project.id)).toBeFocused();
  // Browsing with arrows changes focus only; activation is explicit.
  expect((await activeProject(page)).id).toBe(first.project.id);
  await page.keyboard.press("Enter");
  await expect.poll(() => activeProject(page).then((project) => project.cwd)).toBe(second.project.cwd);
  await expect(select(second.project.id)).toHaveAttribute("aria-current", "page");
  await expect(rail.locator('.project-select[aria-current="page"]')).toHaveCount(1);
  await expect(attention).toBeVisible();
  const beforeHeadingClick = await activeProject(page);
  const identities = () => page.evaluate(async () => (await window.termina.getInstances())
    .map(({ id, cwd, generation, projectId }) => ({ id, cwd, generation, projectId })));
  const beforeInstances = await identities();
  await heading.click();
  expect(await activeProject(page)).toEqual(beforeHeadingClick);
  expect(await identities()).toEqual(beforeInstances);
  await expect(select(second.project.id)).toHaveAttribute("aria-current", "page");
  expect(await page.evaluate((id) => window.termina.runVerify(id), first.owners[0]!)).toEqual({ ok: true });
  await expect(row(first.project.id).locator(".project-attention")).toHaveText("1 attention");
  await expect(row(first.project.id).locator(".project-working")).toHaveText("0 working");
  await expect(row(second.project.id).locator(".project-attention")).toHaveText("0 attention");
  await expect(heading.locator(".attention-count")).toHaveText("1");
  const overview = await page.evaluate(() => window.termina.getWorkOverview());
  expect(overview.items).toHaveLength(1);
  await expect(page.locator("#attention-list")).toContainText(first.project.cwd);
  await expect(select(second.project.id)).toHaveAttribute("aria-current", "page");
  expect((await activeProject(page)).id).toBe(second.project.id);
  await select(first.project.id).focus();
  await page.keyboard.press("Space");
  await expect(attention).toBeVisible();
  await expect.poll(() => activeProject(page).then((project) => project.cwd)).toBe(first.project.cwd);
  await expect(select(first.project.id)).toHaveAttribute("aria-current", "page");
  await expect(rail.locator('.project-select[aria-current="page"]')).toHaveCount(1);
  await select(second.project.id).click();
  await expect.poll(() => activeProject(page).then((project) => project.id)).toBe(second.project.id);
  await expect(attention).toBeVisible();
  const item = overview.items[0]!;
  expect(item.terminalId).toBe(first.owners[0]);
  const canonicalReport = await page.evaluate(({ terminalId, generation }) => window.termina.getVerifyReport(terminalId, generation), item);
  expect(canonicalReport).toContain("FAILED (exit code 7)");
  await page.locator(`#attention-list .attention-item[data-id="${item.id}"] .attention-inspect`).click();
  await expect.poll(() => activeProject(page).then((project) => project.id)).toBe(first.project.id);
  await expect(attention).toBeVisible();
  await expect(heading.locator(".attention-count")).toHaveText("1");
  await expect.poll(() => page.locator(".checks-report").textContent()).toBe(canonicalReport);
  await expect(page.locator(".checks-context")).toContainText(first.owners[0]!);
  await expect(select(first.project.id)).toHaveAttribute("aria-current", "page");
  await expect(rail.locator('.project-select[aria-current="page"]')).toHaveCount(1);
  expect((await page.evaluate(() => window.termina.getInstances())).find((instance) => instance.id === first.owners[0])?.cwd).toBe(first.project.cwd);
  expect(await readVerifyStages(first.project.cwd)).toHaveLength(1);
});
